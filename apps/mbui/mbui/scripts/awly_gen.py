#!/usr/bin/env python3
# The PanGUI layout workloads of arewelayoutyet (benchmarks/pangui/*.txt, from Taffy's benchmarks) as MoonBit builders
# for src/awly: python3 scripts/awly_gen.py <arewelayoutyet>/benchmarks/pangui > src/awly/workloads.mbt
import os, re, sys

TOK = re.compile(r"\s+|//[^\n]*|(-?\d+(?:\.\d+)?)|([A-Za-z_]\w*)|([(){}.])")

def tokens(text):
    out, i = [], 0
    while i < len(text):
        m = TOK.match(text, i)
        if not m:
            raise SystemExit(f"bad character {text[i]!r}")
        i = m.end()
        if m.group(1): out.append(float(m.group(1)))
        elif m.group(2): out.append(m.group(2))
        elif m.group(3): out.append(m.group(3))
    return out

class P:
    def __init__(self, toks): self.t, self.i = toks, 0
    def peek(self): return self.t[self.i] if self.i < len(self.t) else None
    def eat(self, x=None):
        v = self.t[self.i]
        if x is not None and v != x: raise SystemExit(f"expected {x!r}, found {v!r}")
        self.i += 1
        return v
    def num(self):
        v = self.eat()
        if not isinstance(v, float): raise SystemExit(f"expected a number, found {v!r}")
        return v
    def size(self):
        v = self.eat()
        if isinstance(v, float): return f"Px({v})"
        if v in ("Fit", "Expand"):
            w = 1.0
            if self.peek() == "(":
                self.eat("("); w = self.num(); self.eat(")")
            return f"Fit" if v == "Fit" else f"Expand({w})"
        if v in ("Pixels", "Percentage", "Ratio"):
            self.eat("("); x = self.num(); self.eat(")")
            return {"Pixels": "Px", "Percentage": "Frac", "Ratio": "Ratio"}[v] + f"({x})"
        raise SystemExit(f"unknown size {v!r}")
    def node(self):
        props = {}
        while self.peek() != "{":
            name = self.eat()
            self.eat("(")
            if name in ("Width", "Height", "MinWidth", "MinHeight", "MaxWidth", "MaxHeight"):
                key = {"Width": "w", "Height": "h", "MinWidth": "min_w", "MinHeight": "min_h",
                       "MaxWidth": "max_w", "MaxHeight": "max_h"}[name]
                props[key] = self.size()
            elif name == "Gap": props["gap"] = str(self.num())
            elif name.startswith("Padding") or name.startswith("Margin"):
                base = "pad" if name.startswith("Padding") else "mar"
                v = str(self.num())
                sides = {"": "ltrb", "X": "lr", "Y": "tb"}[name[len("Padding" if base == "pad" else "Margin"):]]
                for s in sides: props[f"{base}_{s}"] = v
            elif name == "Wrap": props["wrap"] = "true" if self.eat() == "Auto" else "false"
            elif name == "Horizontal": props["row"] = "true"
            elif name == "Vertical": props["row"] = "false"
            else: raise SystemExit(f"unknown property {name}")
            self.eat(")")
            if self.peek() == ".": self.eat(".")
        self.eat("{")
        kids = self.children()
        self.eat("}")
        return ("node", props, kids)
    def children(self):
        out = []
        while self.peek() not in (None, "}"):
            if self.peek() == "Repeat":
                self.eat(); self.eat("("); n = int(self.num()); self.eat(")"); self.eat("{")
                out.append(("repeat", n, self.children()))
                self.eat("}")
            else:
                out.append(self.node())
        return out

def emit(name, root):
    lines, specs = [], {}
    counter = [0]
    def spec(props):
        args = ", ".join(f"{k}={v}" for k, v in props.items())
        if args not in specs:
            specs[args] = f"s{len(specs)}"
        return specs[args]
    def var():
        counter[0] += 1
        return f"n{counter[0]}"
    def kids(parent, parent_props, items, ind):
        row = parent_props.get("row") == "true"
        for it in items:
            if it[0] == "repeat":
                lines.append(f"{ind}for _ in 0..<{it[1]} {{")
                kids(parent, parent_props, it[2], ind + "  ")
                lines.append(f"{ind}}}")
            else:
                v = var()
                lines.append(f"{ind}let {v} = node({spec(it[1])}, {str(row).lower()})")
                lines.append(f"{ind}{parent}.add({v})")
                kids(v, it[1], it[2], ind)
    lines.append(f"  let root = node({spec(root[1])}, false)")
    kids("root", root[1], root[2], "  ")
    lines.append("  root")
    head = [f"  let {v} = spec({a})" for a, v in specs.items()]
    return f"///|\nfn build_{name}() -> @flex.Node {{\n" + "\n".join(head + lines) + "\n}\n"

def root_size(props, key):
    v = props.get(key, "")
    return v[3:-1] if v.startswith("Px(") else "1000.0"

d = sys.argv[1]
names, out = [], ["// Generated by scripts/awly_gen.py from arewelayoutyet's benchmarks/pangui: do not edit.\n"]
for f in sorted(os.listdir(d)):
    if not f.endswith(".txt"): continue
    text = open(os.path.join(d, f)).read()
    text = re.sub(r"^\s*#\s*Input", "", text, count=1)
    p = P(tokens(text))
    root = p.node()
    name = f[:-4]
    names.append((name, root_size(root[1], "w"), root_size(root[1], "h")))
    out.append(emit(name, root))
out.append("///|\nlet workloads : Array[(String, () -> @flex.Node, Double, Double)] = [\n" +
           "".join(f"  (\"{n}\", build_{n}, {w}, {h}),\n" for n, w, h in names) + "]\n")
print("\n".join(out), end="")
