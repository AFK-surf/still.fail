#!/usr/bin/env python3
"""still.fail's pictures as its Android app draws them, for mbui: the vector
drawables of ember apps/android/shared/src/main/res/drawable (the model
makers' marks, Slack's, still.fail's own mark, the illustrations) and the
station glyphs of its ui/Icons.kt (StationIcons), into src/sf/drawable_data.mbt
as path strings, which src/sf/picture.mbt parses and rasterises.

  python3 scripts/drawables.py <ember> > src/sf/drawable_data.mbt

Each drawable is its viewport and its paths in order, each with its fill
(0xRRGGBBAA, 0 none), its stroke and stroke width, the even-odd rule, and
the transform of the groups it is in (scale, then translate)."""
import os, re, sys
import xml.etree.ElementTree as ET

A = '{http://schemas.android.com/apk/res/android}'

# what Home, sign-in and the station marks use
DRAWABLES = [
    'maker_anthropic', 'maker_openai', 'maker_deepseek', 'maker_qwen', 'maker_zhipu', 'maker_gemini', 'maker_kimi',
    'maker_minimax', 'maker_xai', 'maker_mistral', 'maker_xiaomi', 'maker_ant_ling', 'maker_openrouter',
    'maker_vercel', 'maker_cloudflare', 'maker_azure', 'maker_groq', 'maker_together', 'maker_fireworks',
    'maker_cerebras', 'maker_huggingface', 'maker_nvidia', 'maker_baseten', 'maker_dsh',
    'slack', 'stillfail_mark', 'stillfail_mark_dark',
    'illus_sign_in', 'illus_sign_in_dark', 'illus_new_chat', 'illus_new_chat_dark', 'illus_no_station', 'illus_no_station_dark',
    # the stations' pages (src/sfapp/settings/stations.mbt): the buddy's faces, a station asleep
    'buddy_idle', 'buddy_idle_dark', 'buddy_working', 'buddy_working_dark', 'buddy_offline', 'buddy_offline_dark',
    'illus_station_offline', 'illus_station_offline_dark',
]


def color(v):
    if not v or v == '@android:color/transparent':
        return 0
    v = v.lstrip('#')
    if len(v) == 6:
        return int(v + 'FF', 16)
    if len(v) == 8:
        return int(v[2:] + v[:2], 16)
    raise SystemExit('colour %r' % v)


def num(el, name, default):
    v = el.get(A + name)
    return float(v) if v is not None else default


def walk(el, sx, sy, tx, ty, out):
    for ch in el:
        tag = ch.tag
        if tag == 'group':
            gsx, gsy = num(ch, 'scaleX', 1.0), num(ch, 'scaleY', 1.0)
            gtx, gty = num(ch, 'translateX', 0.0), num(ch, 'translateY', 0.0)
            if ch.get(A + 'rotation') or ch.get(A + 'pivotX') or ch.get(A + 'pivotY'):
                raise SystemExit('a group turned or pivoted: not handled')
            # p' = (p * g_s + g_t) * s + t
            walk(ch, sx * gsx, sy * gsy, gtx * sx + tx, gty * sy + ty, out)
        elif tag == 'path':
            out.append({
                'd': ' '.join(ch.get(A + 'pathData').split()),
                'fill': color(ch.get(A + 'fillColor')),
                'stroke': color(ch.get(A + 'strokeColor')),
                'width': num(ch, 'strokeWidth', 0.0),
                'even_odd': ch.get(A + 'fillType') == 'evenOdd',
                'sx': sx, 'sy': sy, 'tx': tx, 'ty': ty,
            })


def fmt(v):
    s = ('%.4f' % v).rstrip('0').rstrip('.')
    s = s if s not in ('-0', '') else '0'
    return s + '.0' if '.' not in s else s


def mbt_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    ember = sys.argv[1]
    res = os.path.join(ember, 'apps/android/shared/src/main/res/drawable')
    icons = os.path.join(ember, 'apps/android/shared/src/main/kotlin/fail/still/android/ui/Icons.kt')
    print('// Generated by scripts/drawables.py from ember apps/android (res/drawable, ui/Icons.kt): do not edit.')
    print()
    print('///|')
    print('let drawables : Map[String, Drawable] = {')
    for name in DRAWABLES:
        root = ET.parse(os.path.join(res, name + '.xml')).getroot()
        layers = []
        walk(root, 1.0, 1.0, 0.0, 0.0, layers)
        print('  "%s": {' % name)
        print('    w: %s,' % fmt(num(root, 'viewportWidth', 24.0)))
        print('    h: %s,' % fmt(num(root, 'viewportHeight', 24.0)))
        print('    layers: [')
        for l in layers:
            print('      {')
            print('        d: %s,' % mbt_str(l['d']))
            print('        fill: 0x%08XL,' % l['fill'])
            print('        stroke: 0x%08XL,' % l['stroke'])
            print('        width: %s,' % fmt(l['width']))
            print('        even_odd: %s,' % ('true' if l['even_odd'] else 'false'))
            print('        sx: %s,' % fmt(l['sx']))
            print('        sy: %s,' % fmt(l['sy']))
            print('        tx: %s,' % fmt(l['tx']))
            print('        ty: %s,' % fmt(l['ty']))
            print('      },')
        print('    ],')
        print('  },')
    print('}')
    print()
    # StationGlyph("desktop", "🖥️", "words", icon("desktop", listOf("…", "…"), listOf("…")))
    text = open(icons, encoding='utf-8').read()
    body = text[text.index('object StationIcons'):]
    pat = re.compile(r'StationGlyph\("([^"]+)", "([^"]*)", "[^"]*", icon\("[^"]+", listOf\(((?:"[^"]*"(?:, )?)*)\), listOf\(((?:"[^"]*"(?:, )?)*)\)\)\)')
    found = pat.findall(body)
    if len(found) != body.count('StationGlyph("'):
        raise SystemExit('Icons.kt StationIcons: %d glyphs read of %d' % (len(found), body.count('StationGlyph("')))
    print('///|')
    print("/// The station glyphs (StationIcons): each its emoji, its lines (1.75 strokes) and its dots (fills).")
    print('let station_glyphs : Map[String, (String, Array[String], Array[String])] = {')
    for name, emoji, lines, dots in found:
        ls = re.findall(r'"([^"]*)"', lines)
        ds = re.findall(r'"([^"]*)"', dots)
        print('  %s: (%s, [%s], [%s]),' % (mbt_str(name), mbt_str(emoji), ', '.join(mbt_str(x) for x in ls), ', '.join(mbt_str(x) for x in ds)))
    print('}')


main()
