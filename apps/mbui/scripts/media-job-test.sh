#!/bin/bash
# A remote job contains only its input and prebuilt client; only code changes select a different runtime key.
set -eu
D="$(cd "$(dirname "$0")" && pwd)"
cd "$D/.."
source_repo=$(cd ../.. && pwd)
mkdir -p out
take=$(mktemp -d "$PWD/out/media-job-test.XXXXXXXX")
trap 'rm -rf "$take"' EXIT
repo="$take/repo"
mkdir -p "$repo/scripts" "$repo/apps/mbui/scripts" "$repo/apps/mbui/src/example"
mkdir -p "$repo/libs/mbui/src/media/devices"
cp "$source_repo/scripts/native.ts" "$repo/scripts/"
cp scripts/media-job.sh "$repo/apps/mbui/scripts/"
cp ../../libs/mbui/.gitignore "$repo/libs/mbui/.gitignore"
printf '<svg/>\n' > "$repo/libs/mbui/src/media/devices/iphone-11-pro.svg"
printf 'one\n' > "$repo/apps/mbui/src/example/example.mbt"
printf 'generated interface one\n' > "$repo/apps/mbui/src/example/pkg.generated.mbti"
git -C "$repo" init -q
git -C "$repo" add .
printf '{"version":1}\n' > "$take/scene.json"
printf 'exit\n' > "$take/action.drive"
printf 'wait 10\nexit\n' > "$take/prepare.drive"
bash "$repo/apps/mbui/scripts/media-job.sh" figure "$take/scene.json" "$take/first"
printf '{"version":2}\n' > "$take/scene.json"
bash "$repo/apps/mbui/scripts/media-job.sh" figure "$take/scene.json" "$take/second"
cmp "$take/first/runtime.key" "$take/second/runtime.key"
if cmp -s "$take/first/scene.json" "$take/second/scene.json"; then
  echo 'media-job-test: scene change was not copied' >&2; exit 1
fi
printf 'two\n' > "$repo/apps/mbui/src/example/example.mbt"
bash "$repo/apps/mbui/scripts/media-job.sh" figure "$take/scene.json" "$take/changed"
if cmp -s "$take/first/runtime.key" "$take/changed/runtime.key"; then
  echo 'media-job-test: a source change kept the old runtime key' >&2; exit 1
fi
bash "$repo/apps/mbui/scripts/media-job.sh" film "$take/action.drive" "$take/film" "$take/prepare.drive"
[ "$(cat "$take/film/runtime.part")" = mbui-film-wasm ]
bash "$repo/apps/mbui/scripts/media-job.sh" picture "$take/action.drive" "$take/picture" "$take/prepare.drive"
[ "$(cat "$take/picture/runtime.part")" = mbui-film-wasm ]
printf 'generated by moon\n' > "$repo/libs/mbui/src/media/iphone_11_pro.mbt"
bash "$repo/apps/mbui/scripts/media-job.sh" picture "$take/action.drive" "$take/picture-generated"
cmp "$take/picture/runtime.key" "$take/picture-generated/runtime.key"
printf 'generated interface two\n' > "$repo/apps/mbui/src/example/pkg.generated.mbti"
bash "$repo/apps/mbui/scripts/media-job.sh" picture "$take/action.drive" "$take/picture-interface"
cmp "$take/picture/runtime.key" "$take/picture-interface/runtime.key"
printf '<svg id="changed"/>\n' > "$repo/libs/mbui/src/media/devices/iphone-11-pro.svg"
bash "$repo/apps/mbui/scripts/media-job.sh" picture "$take/action.drive" "$take/picture-asset"
if cmp -s "$take/picture/runtime.key" "$take/picture-asset/runtime.key"; then
  echo 'media-job-test: a source asset change kept the old runtime key' >&2; exit 1
fi
cmp "$take/action.drive" "$take/film/action.drive"
cmp "$take/prepare.drive" "$take/film/prepare.drive"
[ ! -e "$take/first/apps" ] && [ ! -e "$take/first/_build" ]
if bash "$repo/apps/mbui/scripts/media-job.sh" figure "$take/scene.json" "$take/first" >/dev/null 2>&1; then
  echo 'media-job-test: an existing job was overwritten' >&2; exit 1
fi

# One prepared job can capture several scenes with the same cached renderer, without overwriting the first result.
cache="$take/cache"
for kind in figure film picture; do
  if [ "$kind" = figure ]; then job="$take/first"; part=mbui-figure; exe=sffigure; launcher=figure-run.sh
  elif [ "$kind" = film ]; then job="$take/film"; part=mbui-film-wasm; exe=sffilm; launcher=media.sh
  else job="$take/picture"; part=mbui-film-wasm; exe=sffilm; launcher=media.sh; fi
  key=$(cat "$job/runtime.key")
  artifact="$cache/$part/darwin-arm64-$key"
  mkdir -p "$artifact"
  : > "$artifact/$exe"
  if [ "$kind" != figure ]; then
    for file in scene.wasm native.node run.mjs compact.mjs; do : > "$artifact/$file"; done
  fi
  printf '{"part":"%s","target":"darwin-arm64","key":"%s"}\n' "$part" "$key" > "$artifact/manifest.json"
  cat > "$artifact/$launcher" <<'LAUNCHER'
#!/bin/bash
printf '%s\n' "$@" > "$MEDIA_TEST_ARGS"
LAUNCHER
done
export STILLFAIL_NATIVE_CACHE="$cache" STILLFAIL_NATIVE=offline MEDIA_TEST_ARGS="$take/args"
bash "$take/film/run.sh"
printf 'picture\n%s\n%s\n%s\n' "$take/film/result.png" "$take/film/action.drive" "$take/film/prepare.drive" > "$take/expected"
cmp "$take/expected" "$take/args"
bash "$take/picture/run.sh" "$take/wasm.png"
printf 'picture\n%s\n%s\n%s\n' "$take/wasm.png" "$take/picture/action.drive" "$take/picture/prepare.drive" > "$take/expected"
cmp "$take/expected" "$take/args"
bash "$take/film/run.sh" "$take/other.png" "$take/action.drive" ''
printf 'picture\n%s\n%s\n' "$take/other.png" "$take/action.drive" > "$take/expected"
cmp "$take/expected" "$take/args"
MBUI_MEDIA_KIND=film bash "$take/film/run.sh" "$take/other.mp4" "$take/action.drive" "$take/prepare.drive"
printf 'film\n%s\n%s\n%s\n' "$take/other.mp4" "$take/action.drive" "$take/prepare.drive" > "$take/expected"
cmp "$take/expected" "$take/args"
bash "$take/first/run.sh" "$take/other-figure.png" "$take/scene.json"
printf '%s\n' --scene "$take/scene.json" "$take/other-figure.png" > "$take/expected"
cmp "$take/expected" "$take/args"
if bash "$take/first/run.sh" a b c >/dev/null 2>&1; then
  echo 'media-job-test: a figure accepted a preparation drive' >&2; exit 1
fi
echo 'media-job-test: source keys, separate scenes and repeated captures passed'
