// MathJax's TeX font split by who uses which half (client/math/README.md): the core lays formulas out with the
// glyphs' sizes alone (src/math-font.ts: the font's tables, each outline in its place replaced by the outline's id);
// the UIs draw the outlines, each once: font.json (the web's) and the app's packed copy
// (apps/mbui/src/sf/math_glyphs.mbt). Run from core-ts after a MathJax TeX font update: node scripts/math-font.ts [--check]
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { gunzipSync, gzipSync } from "node:zlib";
import { MathJaxTexFont } from "@mathjax/mathjax-tex-font/js/svg.js";
import { mathGlyphId } from "../src/mathDrawing.ts";

// deno-lint-ignore no-explicit-any
type J = any;
const FONT = MathJaxTexFont as J;

// The font's own tables (the variants' characters: [height, depth, width, options]), the outline (`p`) of each
// replaced by its id; the outlines by id.
const glyphs: Record<string, string> = {};
const chars: Record<string, Record<string, unknown[]>> = {};
for (const [variant, table] of Object.entries(FONT.defaultChars as Record<string, Record<string, unknown[]>>)) {
  const out: Record<string, unknown[]> = {};
  for (const [code, entry] of Object.entries(table)) {
    const options = entry[3] as { p?: string } | undefined;
    if (typeof options?.p !== "string" || options.p === "") {
      out[code] = entry;
      continue;
    }
    const path = `M${options.p}Z`;
    const id = mathGlyphId(path);
    if (glyphs[id] !== undefined && glyphs[id] !== path) throw new Error(`Math glyph ID collision: ${id}`);
    glyphs[id] = path;
    out[code] = [...entry.slice(0, 3), { ...options, p: id }, ...entry.slice(4)];
  }
  chars[variant] = out;
}
const ids = Object.keys(glyphs).sort((a, b) => parseInt(a, 16) - parseInt(b, 16));

const core =
  "// Generated by scripts/math-font.ts from @mathjax/mathjax-tex-font 4.1.3 (client/math/LICENSE); do not edit. The TeX\n" +
  "// font's tables for the core's layout (math.ts), each glyph's outline in its place replaced by the outline's id: the\n" +
  "// UIs hold the outlines, the core only says which.\n" +
  `export const NAME = ${JSON.stringify(FONT.NAME)};\n` +
  `export const dynamicPrefix = ${JSON.stringify(FONT.OPTIONS.dynamicPrefix)};\n` +
  `export const variantCacheIds: Record<string, string> = ${JSON.stringify(FONT.variantCacheIds)};\n` +
  `export const chars: Record<string, Record<string, unknown[]>> = ${JSON.stringify(chars)};\n`;

// (in the order it always had)
const sorted = Object.fromEntries(Object.entries(glyphs).sort(([a], [b]) => a.localeCompare(b)));
const json = JSON.stringify({ version: "tex-4.1.3", glyphs: sorted }) + "\n";

// mbui's: a u32 count, the ids in order, where each outline starts in what follows (count + 1 offsets), then the
// outlines: each command a byte (M 0, L 1, C 2, Z 3), its coordinates zigzag varints, each from the one before it on
// its axis (from 0 at an outline's start). Little-endian; gzipped. The font's outlines are those commands alone, in
// whole units: anything else is refused, not packed wrong.
function packed(): Uint8Array {
  const data: number[] = [];
  const starts: number[] = [];
  const varint = (n: number) => {
    let v = n < 0 ? -2 * n - 1 : 2 * n;
    while (v >= 0x80) {
      data.push((v & 0x7f) | 0x80);
      v = Math.floor(v / 128);
    }
    data.push(v);
  };
  for (const id of ids) {
    starts.push(data.length);
    const words = glyphs[id]!.match(/[A-Za-z]|-?[0-9.]+/g) ?? [];
    let at = 0;
    let [px, py] = [0, 0];
    while (at < words.length) {
      const op = "MLCZ".indexOf(words[at++]!);
      if (op < 0) throw new Error(`math glyph ${id}: a command other than M L C Z`);
      data.push(op);
      const n = [2, 2, 6, 0][op]!;
      for (let k = 0; k < n; k++) {
        const word = words[at++];
        if (word === undefined || !/^-?[0-9]+$/.test(word)) throw new Error(`math glyph ${id}: not a whole number: ${word}`);
        const v = Number(word);
        if (k % 2 === 0) {
          varint(v - px);
          px = v;
        } else {
          varint(v - py);
          py = v;
        }
      }
    }
  }
  starts.push(data.length);
  const head = new DataView(new ArrayBuffer(4 * (2 + 2 * ids.length)));
  head.setUint32(0, ids.length, true);
  ids.forEach((id, i) => head.setUint32(4 + 4 * i, parseInt(id, 16), true));
  starts.forEach((s, i) => head.setUint32(4 + 4 * ids.length + 4 * i, s, true));
  const out = new Uint8Array(head.byteLength + data.length);
  out.set(new Uint8Array(head.buffer), 0);
  out.set(data, head.byteLength);
  return out;
}

// A MoonBit Bytes literal: printable ASCII as it is, the rest escaped.
const literal = (b: Uint8Array) => {
  let s = "";
  for (const c of b) s += c >= 0x20 && c < 0x7f && c !== 0x22 && c !== 0x5c ? String.fromCharCode(c) : `\\x${c.toString(16).padStart(2, "0")}`;
  return s;
};
const unliteral = (s: string) => {
  const out: number[] = [];
  for (let i = 0; i < s.length; i++) {
    if (s[i] === "\\" && s[i + 1] === "x") {
      out.push(parseInt(s.slice(i + 2, i + 4), 16));
      i += 3;
    } else out.push(s.charCodeAt(i));
  }
  return new Uint8Array(out);
};
const pack = packed();
const nativeHead =
  "// Generated by client/core-ts/scripts/math-font.ts; do not edit. MathJax TeX 4.1.3's outlines (client/math/LICENSE),\n" +
  "// those the core's formulas name (math.mbt), gzipped: a u32 count, the ids in order, where each outline starts (count\n" +
  "// + 1 offsets into what follows), then the outlines: each command a byte (M 0, L 1, C 2, Z 3), its coordinates zigzag\n" +
  "// varints, each from the one before it on its axis. Little-endian.\n" +
  "///|\n// kept across runs: a bundled alphabet, never written\nlet math_glyphs_gz : Bytes = b\"";
const native = (gz: Uint8Array) => nativeHead + literal(gz) + "\"\n";

const coreTarget = new URL("../src/math-font.ts", import.meta.url);
const jsonTarget = new URL("../../math/font.json", import.meta.url);
const nativeTarget = new URL("../../../apps/mbui/src/sf/math_glyphs.mbt", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(coreTarget, "utf8") !== core) throw new Error("The core's math font is stale; regenerate it");
  if (readFileSync(jsonTarget, "utf8") !== json) throw new Error("The bundled math alphabet is stale; regenerate it");
  // By what it holds: gzip's bytes differ between zlib's versions.
  const had = readFileSync(nativeTarget, "utf8");
  const body = had.startsWith(nativeHead) && had.endsWith("\"\n") ? had.slice(nativeHead.length, -2) : null;
  if (body === null || Buffer.compare(gunzipSync(unliteral(body)), pack) !== 0) throw new Error("The native math alphabet is stale; regenerate it");
} else {
  mkdirSync(new URL("../../math/", import.meta.url), { recursive: true });
  writeFileSync(coreTarget, core);
  writeFileSync(jsonTarget, json);
  writeFileSync(nativeTarget, native(gzipSync(pack, { level: 9 })));
}
console.log(`${ids.length} math glyphs: ${Buffer.byteLength(json)} bytes as JSON, ${pack.length} packed`);
