// Regenerate the one shared math alphabet after a MathJax TeX font update. No UI imports MathJax or parses TeX.
// Run from core-ts: node scripts/math-font.ts [--check]
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { MathJaxTexFont } from "@mathjax/mathjax-tex-font/js/svg.js";
import { mathGlyphId } from "../src/mathDrawing.ts";

class PackagedFont extends MathJaxTexFont {
  outlines(): string[] {
    const out: string[] = [];
    for (const variant of Object.values(this.variant)) {
      // Font packages store raw [height, depth, width, options] until getChar materializes CharData.
      for (const entry of Object.values(variant.chars)) {
        if (Array.isArray(entry) && typeof entry[3]?.p === "string" && entry[3].p) out.push(`M${entry[3].p}Z`);
      }
    }
    return out;
  }
}
const glyphs: Record<string, string> = {};
for (const path of new PackagedFont().outlines()) {
    const id = mathGlyphId(path);
    if (glyphs[id] && glyphs[id] !== path) throw new Error(`Math glyph ID collision: ${id}`);
    glyphs[id] = path;
}
const sorted = Object.fromEntries(Object.entries(glyphs).sort(([a], [b]) => a.localeCompare(b)));
const content = JSON.stringify({ version: "tex-4.1.3", glyphs: sorted }) + "\n";
const target = new URL("../../math/font.json", import.meta.url);
const nativeTarget = new URL("../../../apps/mbui/src/sf/math_font.mbt", import.meta.url);
const native = "// Generated by client/core-ts/scripts/math-font.ts. MathJax TeX 4.1.3; see client/math/LICENSE.\n// kept across runs: a bundled alphabet, never written\n///|\nlet math_font_json : String =\n" + JSON.stringify({ version: "tex-4.1.3", glyphs: sorted }, null, 0).split("\n").map((line) => "  #|" + line).join("\n") + "\n";
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== content) throw new Error("The bundled math alphabet is stale; regenerate it");
  if (readFileSync(nativeTarget, "utf8") !== native) throw new Error("The native math alphabet is stale; regenerate it");
} else {
  mkdirSync(new URL("../../math/", import.meta.url), { recursive: true });
  writeFileSync(target, content);
  writeFileSync(nativeTarget, native);
}
console.log(`${Object.keys(glyphs).length} math glyphs, ${Buffer.byteLength(content)} bytes, bundled once per client`);
