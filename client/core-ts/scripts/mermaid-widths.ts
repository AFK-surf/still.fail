// Inter's advances for the core's mermaid (src/mermaid.ts measures a chart's words with them; the app draws them in
// the same face): the face the app carries (apps/mbui/src/sfbase/inter_face.mbt, gzipped in a Bytes literal), read at
// weights 400 and 700 for the characters a chart's labels mostly have. Run from core-ts after Inter changes there:
//   node scripts/mermaid-widths.ts [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { gunzipSync } from "node:zlib";
import * as fontkit from "fontkit";

const RANGES: [number, number][] = [[0x20, 0x24f], [0x370, 0x3ff], [0x400, 0x4ff], [0x2000, 0x206f], [0x20a0, 0x20bf], [0x2100, 0x214f], [0x2190, 0x21ff], [0x2200, 0x22ff], [0x2500, 0x25ff]];

const mbt = readFileSync(new URL("../../../apps/mbui/src/sfbase/inter_face.mbt", import.meta.url), "utf8");
const literal = mbt.slice(mbt.indexOf('b"') + 2, mbt.lastIndexOf('"'));
const bytes: number[] = [];
const escapes: Record<string, number> = { n: 10, t: 9, r: 13, "\\": 92, '"': 34, "'": 39, "0": 0, b: 8 };
for (let i = 0; i < literal.length; ) {
  if (literal[i] !== "\\") { bytes.push(literal.charCodeAt(i++)); continue; }
  const e = literal[i + 1]!;
  if (e === "x") { bytes.push(parseInt(literal.slice(i + 2, i + 4), 16)); i += 4; continue; }
  const b = escapes[e];
  if (b === undefined) throw new Error(`escape \\${e} in inter_face.mbt`);
  bytes.push(b);
  i += 2;
}
// deno-lint-ignore no-explicit-any
const font = fontkit.create(gunzipSync(Buffer.from(bytes))) as any;

// Each range's advances, one weight after the other, in font units; 0 where Inter has no glyph (measured as another
// face's then: src/mermaid.ts).
const weights: Record<string, number[][]> = {};
for (const wght of [400, 700]) {
  const f = font.getVariation({ wght });
  weights[wght] = RANGES.map(([a, b]) => {
    const out: number[] = [];
    for (let c = a; c <= b; c++) out.push(font.hasGlyphForCodePoint(c) ? Math.round(f.glyphForCodePoint(c).advanceWidth) : 0);
    return out;
  });
}

const text =
  "// Generated by scripts/mermaid-widths.ts from Inter 4.001 as the app carries it (SIL Open Font License); do not edit.\n" +
  "// Its advances in font units at weights 400 and 700, range by range (0: no glyph in Inter).\n" +
  `export const UNITS = ${font.unitsPerEm};\n` +
  `export const ASCENT = ${font.hhea.ascent};\n` +
  `export const DESCENT = ${-font.hhea.descent};\n` +
  `export const RANGES: [number, number][] = ${JSON.stringify(RANGES)};\n` +
  `export const W400: number[][] = ${JSON.stringify(weights[400])};\n` +
  `export const W700: number[][] = ${JSON.stringify(weights[700])};\n`;
const out = new URL("../src/mermaid-widths.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(out, "utf8") !== text) throw new Error("src/mermaid-widths.ts is not what Inter makes: run node scripts/mermaid-widths.ts");
} else writeFileSync(out, text);
