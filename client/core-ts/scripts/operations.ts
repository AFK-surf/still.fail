// The UIs' bindings of the core's operations, made from their contracts (src/ops.ts `PARAMS`): web/src/core/operations.ts
// and the Android app's data/Operations.kt. `node scripts/operations.ts` writes them; `--check` fails when they are
// not what the contracts make. Optional fields keep "left out" apart from an explicit null; bodies the core leaves
// open (input/settings/state/access) stay JSON.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { PARAMS, QUIET_WRITES, request } from "../src/ops.ts";

const repo = (path: string) => fileURLToPath(new URL(`../../../${path}`, import.meta.url));
const SAID = "Generated by client/core-ts/scripts/operations.ts from client/core-ts/src/ops.ts. Do not edit.";
type Field = [name: string, type: string, required: boolean];

const rows: [scope: "station" | "account", name: string, fields: Field[]][] = Object.entries(PARAMS).map(([name, contract]) => {
  const fields: Field[] = contract.split(/\s+/).filter(Boolean).map((word) => {
    const [field, type] = word.split(":");
    return [field.replace(/\?$/, ""), type, !field.endsWith("?")];
  });
  const service = name.slice(0, name.indexOf("."));
  return [["workspace", "invitation", "loginSession", "admin"].includes(service) ? "account" : "station", name, fields];
});

const SAMPLE: Record<string, unknown> = { string: "x", number: 1, boolean: true, strings: ["x"], json: {} };
/// A read: what the UI does not see being done (its method GET), as the core asks it.
function reads(name: string, fields: Field[]): boolean {
  const params: Record<string, unknown> = { station: "w/s", account: "a" };
  for (const [k, type] of fields) params[k] = SAMPLE[type];
  return request(name, params)?.method === "GET";
}
const untracked = [...new Set([...rows.filter(([, name, fields]) => reads(name, fields)).map(([, name]) => name), ...QUIET_WRITES])].sort();

const camel = (name: string) => {
  const [a, b] = name.split(".");
  return a + b[0].toUpperCase() + b.slice(1);
};

function typescript(): string {
  const types: Record<string, string> = { string: "string", number: "number", boolean: "boolean", strings: "string[]", json: "unknown" };
  const ts = [`// ${SAID}`, "export interface OperationParams {"];
  for (const [, name, fields] of rows) {
    ts.push(`  "${name}": { ${fields.map(([k, t, req]) => `${k}${req ? "" : "?"}: ${types[t]}${req || t === "json" ? "" : " | null | undefined"}`).join("; ")} };`);
  }
  ts.push("}", "", `export const UNTRACKED_OPERATIONS = new Set(${JSON.stringify(untracked).replace(/","/g, '", "')});`, "", "type Call = (name: string, params: Record<string, unknown>) => Promise<unknown>;", "");
  for (const [scope, cls] of [["station", "Station"], ["account", "Cloud"]] as const) {
    ts.push(`export function bind${cls}Operations(call: Call) {`, "  return {");
    for (const [sc, name, fields] of rows) {
      if (sc !== scope) continue;
      const def = fields.some(([, , req]) => req) ? "" : " = {}";
      ts.push(`    ${camel(name)}: <T = unknown>(params: OperationParams["${name}"]${def}) => call("${name}", params) as Promise<T>,`);
    }
    ts.push("  };", "}", "");
  }
  return ts.join("\n");
}

function kotlin(): string {
  const kt = [
    `// ${SAID}`,
    "package fail.still.android.data",
    "",
    "import kotlinx.serialization.json.*",
    "import kotlin.properties.ReadWriteProperty",
    "import kotlin.reflect.KProperty",
    "",
    "/** A field is absent until assigned; assigning null sends JSON null (reset to default). */",
    `val UNTRACKED_OPERATIONS = setOf(${untracked.map((n) => `"${n}"`).join(", ")})`,
    "",
    "open class OperationFields {",
    "    internal val fields = mutableMapOf<String, JsonElement>()",
    "    protected fun <T> field(name: String, encode: (T) -> JsonElement) = object : ReadWriteProperty<Any?, T?> {",
    "        private var value: T? = null",
    "        override fun getValue(thisRef: Any?, property: KProperty<*>): T? = value",
    "        override fun setValue(thisRef: Any?, property: KProperty<*>, value: T?) {",
    "            this.value = value; fields[name] = value?.let(encode) ?: JsonNull",
    "        }",
    "    }",
    "}",
    "",
  ];
  const types: Record<string, string> = { string: "String", number: "Long", boolean: "Boolean", strings: "List<String>", json: "JsonElement" };
  const enc: Record<string, string> = { string: "JsonPrimitive(it)", number: "JsonPrimitive(it)", boolean: "JsonPrimitive(it)", strings: "JsonArray(it.map(::JsonPrimitive))", json: "it" };
  for (const [scope, cls] of [["station", "Station"], ["account", "Cloud"]] as const) {
    kt.push(`class ${cls}Operations(private val call: suspend (String, JsonObject) -> JsonElement) {`);
    for (const [sc, name, fields] of rows) {
      if (sc !== scope) continue;
      const method = camel(name);
      const klass = `${method[0].toUpperCase()}${method.slice(1)}Fields`;
      const required = fields.filter(([, , r]) => r);
      const optional = fields.filter(([, , r]) => !r);
      if (optional.length > 0) {
        kt.push(`    class ${klass} : OperationFields() {`);
        for (const [k, t] of optional) kt.push(`        var ${k}: ${types[t]}? by field<${types[t]}>("${k}") { ${enc[t]} }`);
        kt.push("    }");
      }
      const params = required.map(([k, t]) => `${k}: ${types[t]}`);
      if (optional.length > 0) params.push(`fill: ${klass}.() -> Unit = {}`);
      kt.push(`    suspend fun ${method}(${params.join(", ")}): JsonElement {`);
      kt.push(optional.length > 0 ? `        val values = ${klass}().apply(fill).fields` : "        val values = mutableMapOf<String, JsonElement>()");
      for (const [k, t] of required) kt.push(`        values["${k}"] = ${enc[t].replace(/\bit\b/g, k)}`);
      kt.push(`        return call("${name}", JsonObject(values))`, "    }");
    }
    kt.push("}", "");
  }
  return kt.join("\n");
}

const made: [string, string][] = [
  [repo("web/src/core/operations.ts"), typescript()],
  [repo("apps/android/app/src/main/kotlin/fail/still/android/data/Operations.kt"), kotlin()],
];
if (process.argv.includes("--check")) {
  const stale = made.filter(([path, text]) => readFileSync(path, "utf8") !== text);
  if (stale.length > 0) {
    console.error(`not what client/core-ts/src/ops.ts makes: ${stale.map(([p]) => p).join(", ")} — run node client/core-ts/scripts/operations.ts`);
    process.exit(1);
  }
} else for (const [path, text] of made) writeFileSync(path, text);
