// Older core tapes precede the Markdown operation. Keep its pure answers beside those tapes, produced by the
// real core, so the replay's Source can answer without a second parser or inventing a network interaction.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { markdown } from "../src/markdown.ts";
const traces = new URL("../../../apps/mbui/e2e/traces/", import.meta.url);
const texts = new Set<string>();
function collect(value: unknown): void {
  if (Array.isArray(value)) { value.forEach(collect); return; }
  if (!value || typeof value !== "object") return;
  for (const [key, child] of Object.entries(value)) {
    if (["text", "content", "answer", "summary"].includes(key) && typeof child === "string") texts.add(child);
    collect(child);
  }
}
for (const name of readdirSync(traces).sort()) {
  if (!name.endsWith(".trace")) continue;
  for (const line of readFileSync(new URL(name, traces), "utf8").split("\n")) {
    try { collect(JSON.parse(line)); } catch { /* A tape also carries its host's non-JSON diagnostics. */ }
  }
}
const answers = JSON.stringify(Object.fromEntries([...texts].sort().map(text => [text, markdown(text)])));
const content = "// Generated by client/core-ts/scripts/replay-markdown.ts from the kept tapes' words, using the real core.\n///|\nlet markdown_answers : String =\n  #|" + answers + "\n";
const target = new URL("../../../apps/mbui/src/sfreplay/markdown_answers.mbt", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== content) throw new Error("Replay Markdown answers changed: run client/core-ts/scripts/replay-markdown.ts");
} else writeFileSync(target, content);
console.log(`${texts.size} pure core Markdown answers for the older tapes`);
