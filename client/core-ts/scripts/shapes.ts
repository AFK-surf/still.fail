// The clients' types, made from the shapes the core declares (src/shapes/schema.ts): web/src/core/shapes.ts, the ones
// the web's pages and the tests import from it (and what those name); and
// for the mbui app's squeeze sweep, where each topic holds words someone outside the app wrote (a field marked `said`):
// apps/mbui/src/sffixture/said_paths.mbt.
// `node scripts/shapes.ts` writes them; `--check` fails when they are not what the shapes make (scripts/check.sh and CI
// run it, so the clients' types cannot drift from what the core sends).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import type { Field, Shape, Ty } from "../src/shapes/dsl.ts";
import { SHAPES, TOPIC_SHAPES } from "../src/shapes/schema.ts";

const repo = (path: string) => fileURLToPath(new URL(`../../../${path}`, import.meta.url));
const TS = repo("web/src/core/shapes.ts");
const SAID_PATHS = repo("apps/mbui/src/sffixture/said_paths.mbt");
const SAID = "Generated by client/core-ts/scripts/shapes.ts from client/core-ts/src/shapes/schema.ts: do not edit.";

/// The shapes a type names, in the order it names them.
function named(ty: Ty, out: string[] = []): string[] {
  if (typeof ty === "string") out.push(ty);
  else if ("opt" in ty) named(ty.opt, out);
  else if ("vec" in ty) named(ty.vec, out);
  else if ("map" in ty) named(ty.map, out);
  else for (const t of ty.tuple) named(t, out);
  return out;
}

/// The shapes the web's pages and the tests import from web/src/core/shapes.ts: the file has those alone.
function imported(): string[] {
  const names = new Set<string>();
  const walk = (dir: string) => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, e.name);
      if (e.isDirectory()) { if (e.name !== "node_modules" && e.name !== "iroh-pkg") walk(path); continue; }
      if (!/\.(ts|tsx)$/.test(e.name) || path === TS) continue;
      for (const m of readFileSync(path, "utf8").matchAll(/import\s+(?:type\s+)?\{([^}]*)\}\s+from\s+"[^"]*core\/shapes\.ts"/g)) {
        for (const part of m[1]!.split(",")) {
          const name = part.trim().replace(/^type\s+/, "").split(/\s+as\s+/)[0]!.trim();
          if (name) names.add(name);
        }
      }
    }
  };
  walk(repo("web"));
  walk(repo("test"));
  return [...names].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

/// The structs by name, each after the shapes its fields name; a set of words or a union just before the first struct
/// that names it (the order typeshare gave them, so the files did not move when it went).
function ordered(): [string, Shape][] {
  const out: [string, Shape][] = [];
  const seen = new Set<string>();
  const visit = (name: string) => {
    const shape = SHAPES[name];
    if (seen.has(name) || !shape?.client) return;
    seen.add(name);
    if (shape.kind === "struct") for (const f of shape.fields) for (const n of named(f.client ?? f.ty)) visit(n);
    out.push([name, shape]);
  };
  for (const name of imported()) visit(name);
  return out;
}

// ── TypeScript ──

const NUMBERS = new Set(["I54", "i64", "i32", "u64", "u32", "u16", "u8", "usize", "f64", "f32"]);

function tsTy(ty: Ty): string {
  if (typeof ty === "string") return ty === "String" ? "string" : ty === "bool" ? "boolean" : NUMBERS.has(ty) ? "number" : ty === "Value" ? "unknown" : ty;
  if ("opt" in ty) return tsTy(ty.opt);
  if ("vec" in ty) return `${tsTy(ty.vec)}[]`;
  if ("map" in ty) return `Record<string, ${tsTy(ty.map)}>`;
  return `[${ty.tuple.map(tsTy).join(", ")}]`;
}

function tsDoc(doc: string | undefined, indent: string): string {
  if (doc === undefined) return "";
  const lines = doc.split("\n");
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`;
  return `${indent}/**\n${lines.map((l) => `${indent} *${l === "" ? "" : ` ${l}`}`).join("\n")}\n${indent} */\n`;
}

function typescript(): string {
  let out = `/*\n ${SAID}\n*/\n\n`;
  for (const [name, s] of ordered()) {
    out += tsDoc(s.doc, "");
    if (s.kind === "enum") out += `export type ${name} = ${s.values.map((v) => JSON.stringify(v)).join(" | ")};\n\n`;
    else if (s.kind === "tagged") {
      out += `export type ${name} = \n${Object.entries(s.variants).map(([w, ty]) => `\t| { ${s.tag}: ${JSON.stringify(w)}, ${s.content}: ${tsTy(ty)} }`).join("\n")};\n\n`;
    } else {
      out += `export interface ${name} {\n`;
      for (const f of s.fields) {
        const ty = f.client ?? f.ty;
        const optional = (typeof ty === "object" && "opt" in ty) || f.default;
        out += `${tsDoc(f.doc, "\t")}\t${f.name}${optional ? "?" : ""}: ${tsTy(ty)};\n`;
      }
      out += "}\n\n";
    }
  }
  return out;
}

// ── Where outside words are, for mbui ──

/// The paths in a value of type `ty` to its words a field's `pick` takes (marked `said`, or with a `widest`): its fields
/// by name, `*` each item of a list or a map, `<tag>=<word>` a union's variant (where its tag says that word), then its
/// content by its field; a shape already on the way down not entered again. Each with what `pick` gave of its field.
function pathsTo<T>(pick: (f: Field) => T | undefined, ty: Ty, at: string[], within: string[], out: [string, T][]) {
  if (typeof ty !== "string") {
    if ("opt" in ty) pathsTo(pick, ty.opt, at, within, out);
    else if ("vec" in ty) pathsTo(pick, ty.vec, [...at, "*"], within, out);
    else if ("map" in ty) pathsTo(pick, ty.map, [...at, "*"], within, out);
    return;
  }
  const shape = SHAPES[ty];
  if (shape === undefined || within.includes(ty)) return;
  if (shape.kind === "struct") {
    for (const f of shape.fields) {
      const got = pick(f);
      if (got !== undefined) {
        let words: Ty = f.ty;
        const path = [...at, f.name];
        while (typeof words === "object") {
          if ("opt" in words) words = words.opt;
          else if ("vec" in words) { words = words.vec; path.push("*"); }
          else if ("map" in words) { words = words.map; path.push("*"); }
          else break;
        }
        if (words !== "String") throw new Error(`${ty}.${f.name}: said or widest, but not words`);
        out.push([path.join("."), got]);
      } else pathsTo(pick, f.ty, [...at, f.name], [...within, ty], out);
    }
  } else if (shape.kind === "tagged") {
    for (const [word, v] of Object.entries(shape.variants)) {
      pathsTo(pick, v, [...at, `${shape.tag}=${word}`, shape.content], [...within, ty], out);
    }
  }
}

function mbuiSaid(): string {
  let out = `// ${SAID}\n// Where each topic the core shapes holds words someone outside the app wrote (a field marked \`said\`), a path each:\n`;
  out += "// its fields by name, `*` each item of a list or a map, `<tag>=<word>` a union's variant; and where it holds a figure\n";
  out += "// the core writes (a field with a `widest`), a path each with that. The fixtures make them their longest and widest\n";
  out += "// for the squeeze sweep's stretched pass and sffix's MBUI_SAID (fixture_said.mbt).\n\n";
  out += "///|\n// kept across runs: a value (never changed)\npub let said_paths : Map[String, Array[String]] = {\n";
  for (const topic of Object.keys(TOPIC_SHAPES).sort()) {
    const paths: [string, true][] = [];
    pathsTo((f) => f.said ? true : undefined, TOPIC_SHAPES[topic]!, [], [], paths);
    const unique = [...new Set(paths.map(([p]) => p))];
    if (unique.length === 0) continue;
    out += `  ${JSON.stringify(topic)}: [\n${unique.map((p) => `    ${JSON.stringify(p)},\n`).join("")}  ],\n`;
  }
  out += "}\n\n///|\n// kept across runs: a value (never changed)\npub let widest_paths : Map[String, Array[(String, String)]] = {\n";
  for (const topic of Object.keys(TOPIC_SHAPES).sort()) {
    const paths: [string, string][] = [];
    pathsTo((f) => f.widest, TOPIC_SHAPES[topic]!, [], [], paths);
    const seen = new Set<string>();
    const unique = paths.filter(([p]) => !seen.has(p) && seen.add(p) !== undefined);
    if (unique.length === 0) continue;
    out += `  ${JSON.stringify(topic)}: [\n${unique.map(([p, w]) => `    (${JSON.stringify(p)}, ${JSON.stringify(w)}),\n`).join("")}  ],\n`;
  }
  return out + "}\n";
}

const made: [string, string][] = [
  [TS, typescript()],
  [SAID_PATHS, mbuiSaid()],
];
if (process.argv.includes("--check")) {
  const stale = made.filter(([path, text]) => readFileSync(path, "utf8") !== text);
  if (stale.length > 0) {
    console.error(`not what client/core-ts/src/shapes/schema.ts makes: ${stale.map(([p]) => p).join(", ")} — run node client/core-ts/scripts/shapes.ts`);
    process.exit(1);
  }
} else {
  for (const [path, text] of made) writeFileSync(path, text);
  console.log(`${ordered().length} types`);
}
