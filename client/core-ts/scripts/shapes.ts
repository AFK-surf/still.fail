// The clients' types, made from the shapes the core declares (src/shapes/schema.ts): web/src/core/shapes.ts and the
// Android app's data/Shapes.kt. `node scripts/shapes.ts` writes them; `--check` fails when they are not what the
// shapes make (scripts/check.sh and CI run it, so the clients' types cannot drift from what the core sends).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { Shape, Ty } from "../src/shapes/dsl.ts";
import { SHAPES } from "../src/shapes/schema.ts";

const repo = (path: string) => fileURLToPath(new URL(`../../../${path}`, import.meta.url));
const TS = repo("web/src/core/shapes.ts");
const KT = repo("apps/android/app/src/main/kotlin/fail/still/android/data/Shapes.kt");
const SAID = "Generated by client/core-ts/scripts/shapes.ts from client/core-ts/src/shapes/schema.ts: do not edit.";

const shared = Object.entries(SHAPES).filter(([, s]) => s.client);

/// The shapes a type names, in the order it names them.
function named(ty: Ty, out: string[] = []): string[] {
  if (typeof ty === "string") out.push(ty);
  else if ("opt" in ty) named(ty.opt, out);
  else if ("vec" in ty) named(ty.vec, out);
  else if ("map" in ty) named(ty.map, out);
  else for (const t of ty.tuple) named(t, out);
  return out;
}

/// The structs by name, each after the shapes its fields name; a set of words or a union just before the first struct
/// that names it (the order typeshare gave them, so the files did not move when it went).
function ordered(): [string, Shape][] {
  const out: [string, Shape][] = [];
  const seen = new Set<string>();
  const visit = (name: string) => {
    const shape = SHAPES[name];
    if (seen.has(name) || !shape?.client) return;
    seen.add(name);
    if (shape.kind === "struct") for (const f of shape.fields) for (const n of named(f.client ?? f.ty)) visit(n);
    out.push([name, shape]);
  };
  const structs = shared.filter(([, s]) => s.kind === "struct").map(([n]) => n);
  for (const name of structs.sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))) visit(name);
  // What no struct names comes last.
  for (const [name] of shared) visit(name);
  return out;
}

// ── TypeScript ──

const NUMBERS = new Set(["I54", "i64", "i32", "u64", "u32", "u16", "u8", "usize", "f64", "f32"]);

function tsTy(ty: Ty): string {
  if (typeof ty === "string") return ty === "String" ? "string" : ty === "bool" ? "boolean" : NUMBERS.has(ty) ? "number" : ty === "Value" ? "unknown" : ty;
  if ("opt" in ty) return tsTy(ty.opt);
  if ("vec" in ty) return `${tsTy(ty.vec)}[]`;
  if ("map" in ty) return `Record<string, ${tsTy(ty.map)}>`;
  return `[${ty.tuple.map(tsTy).join(", ")}]`;
}

function tsDoc(doc: string | undefined, indent: string): string {
  if (doc === undefined) return "";
  const lines = doc.split("\n");
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`;
  return `${indent}/**\n${lines.map((l) => `${indent} *${l === "" ? "" : ` ${l}`}`).join("\n")}\n${indent} */\n`;
}

function typescript(): string {
  let out = `/*\n ${SAID}\n*/\n\n`;
  for (const [name, s] of ordered()) {
    out += tsDoc(s.doc, "");
    if (s.kind === "enum") out += `export type ${name} = ${s.values.map((v) => JSON.stringify(v)).join(" | ")};\n\n`;
    else if (s.kind === "tagged") {
      out += `export type ${name} = \n${Object.entries(s.variants).map(([w, ty]) => `\t| { ${s.tag}: ${JSON.stringify(w)}, ${s.content}: ${tsTy(ty)} }`).join("\n")};\n\n`;
    } else {
      out += `export interface ${name} {\n`;
      for (const f of s.fields) {
        const ty = f.client ?? f.ty;
        const optional = (typeof ty === "object" && "opt" in ty) || f.default;
        out += `${tsDoc(f.doc, "\t")}\t${f.name}${optional ? "?" : ""}: ${tsTy(ty)};\n`;
      }
      out += "}\n\n";
    }
  }
  return out;
}

// ── Kotlin ──

const KOTLIN: Record<string, string> = { String: "String", bool: "Boolean", I54: "Long", i64: "Long", i32: "Int", u64: "ULong", u32: "UInt", u16: "UShort", u8: "UByte", usize: "ULong", f64: "Double", f32: "Float", Value: "JsonElement" };

function ktTy(ty: Ty): string {
  if (typeof ty === "string") return KOTLIN[ty] ?? ty;
  if ("opt" in ty) return `${ktTy(ty.opt)}?`;
  if ("vec" in ty) return `List<${ktTy(ty.vec)}>`;
  if ("map" in ty) return `Map<String, ${ktTy(ty.map)}>`;
  throw new Error("Kotlin has no tuples here");
}

const ktDoc = (doc: string | undefined, indent: string) => (doc === undefined ? "" : doc.split("\n").map((l) => `${indent}///${l === "" ? "" : ` ${l}`}\n`).join(""));

function kotlin(): string {
  const items = ordered();
  const unions = items.some(([, s]) => s.kind === "tagged");
  let out = `/**\n * ${SAID}\n */\n\npackage fail.still.android.data\n\nimport kotlinx.serialization.Serializable\nimport kotlinx.serialization.SerialName\n`;
  if (unions) out += "import kotlinx.serialization.ExperimentalSerializationApi\nimport kotlinx.serialization.json.JsonClassDiscriminator\n";
  out += "\n";
  for (const [name, s] of items) {
    out += ktDoc(s.doc, "");
    if (s.kind === "enum") out += `typealias ${name} = String\n\n`;
    else if (s.kind === "tagged") {
      out += `@OptIn(ExperimentalSerializationApi::class)\n@JsonClassDiscriminator(${JSON.stringify(s.tag)})\n@Serializable\nsealed class ${name} {\n`;
      for (const [w, ty] of Object.entries(s.variants)) out += `\t@Serializable\n\t@SerialName(${JSON.stringify(w)})\n\tdata class ${s.names[w]}(val ${s.content}: ${ktTy(ty)}): ${name}()\n`;
      out += "}\n\n";
    } else {
      out += `@Serializable\ndata class ${name} (\n`;
      out += s.fields
        .map((f) => {
          const ty = f.client ?? f.ty;
          // A field read with a default when missing is optional to the clients too (as typeshare had it).
          const opt = typeof ty === "object" && "opt" in ty;
          const optional = opt || f.default;
          return `${ktDoc(f.doc, "\t")}\tval ${f.name}: ${ktTy(ty)}${optional && !opt ? "?" : ""}${optional ? " = null" : ""}`;
        })
        .join(",\n");
      out += "\n)\n\n";
    }
  }
  return out;
}

const made: [string, string][] = [
  [TS, typescript()],
  [KT, kotlin()],
];
if (process.argv.includes("--check")) {
  const stale = made.filter(([path, text]) => readFileSync(path, "utf8") !== text);
  if (stale.length > 0) {
    console.error(`not what client/core-ts/src/shapes/schema.ts makes: ${stale.map(([p]) => p).join(", ")} — run node client/core-ts/scripts/shapes.ts`);
    process.exit(1);
  }
} else {
  for (const [path, text] of made) writeFileSync(path, text);
  console.log(`${ordered().length} types`);
}
