#!/usr/bin/env python3
"""Generates src/text/bidi_tables.mbt (Bidi_Class, the paired brackets) and
src/text/bidi_conformance_test.mbt (a sample of BidiCharacterTest.txt) from
the UCD, the way scripts/gen_unicode.py makes the other tables.

    UCD_VERSION=18.0.0 python3 scripts/gen_bidi.py

EVERY=n keeps one case in n of BidiCharacterTest.txt (default 12).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_unicode as g  # noqa: E402

g.FILES.update({
    "DerivedBidiClass.txt": "extracted/DerivedBidiClass.txt",
    "BidiBrackets.txt": "BidiBrackets.txt",
    "BidiCharacterTest.txt": "BidiCharacterTest.txt",
    "BidiMirroring.txt": "BidiMirroring.txt",
})

CLASSES = ["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON",
           "LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"]


def main():
    dbc = g.fetch("DerivedBidiClass.txt")
    ver = g.version_of(dbc)
    cls = g.parse(dbc, "L")
    # the @missing lines name classes in full
    long = {"Left_To_Right": "L", "Right_To_Left": "R", "Arabic_Letter": "AL", "European_Number": "EN",
            "European_Separator": "ES", "European_Terminator": "ET", "Arabic_Number": "AN",
            "Common_Separator": "CS", "Nonspacing_Mark": "NSM", "Boundary_Neutral": "BN",
            "Paragraph_Separator": "B", "Segment_Separator": "S", "White_Space": "WS", "Other_Neutral": "ON"}
    vals = [CLASSES.index(long.get(c, c)) for c in cls]
    rs = g.ranges(vals)
    enc = g.encode(rs)
    pairs = []
    for line in g.fetch("BidiBrackets.txt").splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        a, b, t = [p.strip() for p in line.split(";")]
        pairs.append((int(a, 16), int(b, 16), 1 if t == "o" else 2))
    out = [
        "// Generated by scripts/gen_bidi.py from the Unicode %s character database. Do not edit.\n\n" % ver,
        g.literal("bidi_data", enc, "%d ranges: Bidi_Class (the constants below)" % len(rs)),
        "\n///|\n/// Bidi_Paired_Bracket pairs: code point, its pair, 1 opening or 2 closing\n",
        "let bidi_brackets : FixedArray[Int] = [\n",
    ]
    for a, b, t in pairs:
        out.append("  0x%X, 0x%X, %d,\n" % (a, b, t))
    out.append("]\n")
    mirrors = []
    for line in g.fetch("BidiMirroring.txt").splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        a, b = [p.strip() for p in line.split(";")]
        mirrors.append((int(a, 16), int(b, 16)))
    out.append("\n///|\n/// Bidi_Mirroring_Glyph: code point, the one drawn for it in right-to-left text\n")
    out.append("let bidi_mirrors : FixedArray[Int] = [\n")
    for a, b in mirrors:
        out.append("  0x%X, 0x%X,\n" % (a, b))
    out.append("]\n\n// Bidi_Class values.\n")
    for i, k in enumerate(CLASSES):
        out.append("\n///|\nconst B_%s = %d\n" % (k, i))
    with open(os.path.join(g.ROOT, "src", "text", "bidi_tables.mbt"), "w") as f:
        f.write("".join(out))
    print("Unicode %s: %d Bidi_Class ranges (%d chars), %d brackets" % (ver, len(rs), len(enc), len(pairs)))

    every = int(os.environ.get("EVERY", "12"))
    text = g.fetch("BidiCharacterTest.txt")
    cases = []
    k = 0
    for line in text.splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        k += 1
        if k % every:
            continue
        cps, pdir, plevel, levels, order = [p.strip() for p in line.split(";")]
        cases.append("%s;%s;%s;%s;%s" % (cps.replace(" ", ","), pdir, plevel, levels.replace(" ", ","),
                                          order.replace(" ", ",")))
    names = []
    out = [
        "// Generated by scripts/gen_bidi.py from BidiCharacterTest.txt (Unicode %s, one case in %d). Do not edit.\n"
        "// One case a line: code points; paragraph direction (0 LTR, 1 RTL, 2 auto); its resolved level;\n"
        "// each character's level (x: removed by X9); the visual order.\n" % (ver, every)
    ]
    chunk = 2000
    for i in range(0, len(cases), chunk):
        names.append("bidi_cases_%d" % len(names))
        out.append("\n///|\nlet %s : String =\n  (\n" % names[-1])
        for c in cases[i:i + chunk]:
            out.append("    #|%s\n" % c)
        out.append("  )\n")
    out.append("\n///|\ntest \"bidi conformance (BidiCharacterTest.txt, Unicode %s)\" {\n"
               "  run_bidi_conformance([%s])\n}\n" % (ver, ", ".join(names)))
    with open(os.path.join(g.ROOT, "src", "text", "bidi_conformance_test.mbt"), "w") as f:
        f.write("".join(out))
    print("BidiCharacterTest.txt: %d of %d cases" % (len(cases), k))


if __name__ == "__main__":
    sys.exit(main())
