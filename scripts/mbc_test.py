SRC = PRELUDE + '\n' + ITEMS


class Split(unittest.TestCase):
    def test_kinds(self):
        files, m = csplit.split(SRC, 2)
        s = m['stats']
        self.assertEqual(m['functions'], 5)
        self.assertEqual(m['globals'], 4)
        self.assertEqual(s['types'], 3)
        self.assertEqual(s['statics_dropped'], 1)
        self.assertEqual(s['prelude_definitions'], 2)
        self.assertIn('#ifdef CSPLIT_DEFS\n/* the prelude', files['decls.h'])
        self.assertIn('  return x * 2;\n}\n#else\nint32_t pre_twice(int32_t x);\n#endif', files['decls.h'])
        self.assertIn('#else\nextern const int32_t pre_tab[2];\n#endif', files['decls.h'])
        self.assertTrue(files['data.c'].index('#define CSPLIT_DEFS') < files['data.c'].index('#include "decls.h"'))
        self.assertEqual(m['made_global'], ['_M0FP1a6hidden'])
        self.assertIn('#define _M0FP1a3ffi puts', files['decls.h'])
        self.assertIn('static inline int32_t helper', files['decls.h'])
        self.assertIn('extern struct { int32_t rc; uint32_t meta; uint16_t const data[3]; } const _M0S1;',
                      files['externs.h'])
        self.assertIn('extern int32_t _M0G2;', files['externs.h'])
        self.assertIn('extern const char _M0G3[];', files['externs.h'])
        self.assertIn('void moonbit_init()', files['init.c'])
        self.assertNotIn('moonbit_init()  {', files['f0.c'] + files['f1.c'])
        # every function in exactly one unit, and static no more
        body = files['f0.c'] + files['f1.c']
        for name in ('_M0FP1a6hidden(int32_t x) {', '_M0FP1a3add(int32_t a', '_M0FP1a3get() {', 'int main('):
            self.assertEqual(body.count(name), 1, name)
        self.assertNotIn('static int32_t _M0FP1a6hidden', body)
        self.assertIn('CSPLIT_INTERNAL int32_t _M0FP1a6hidden(int32_t x) {', body)
        self.assertIn('#define CSPLIT_INTERNAL __attribute__((visibility("hidden")))', files['decls.h'])
        # a prototype for the function moonc defined without one
        self.assertIn('int32_t _M0FP1a6hidden(int32_t x);', files['decls.h'])
        self.assertIn('void moonbit_init();', files['decls.h'])
        self.assertNotIn('_M0G1 = {', files['decls.h'] + files['externs.h'])

    def test_stable(self):
        """group 'stable': moonc's made-up numbers (locals, labels, anonymous functions, string literals) another
        build numbers otherwise give the same units; a package's functions in its unit, with only what they use."""
        def prog(n, extra=''):
            return PRELUDE + '\n' + textwrap.dedent(f'''\
                struct _M0TP11a1T;

                struct _M0TP11a1T {{
                  int32_t x;
                }};

                struct _M0TP11b1U {{
                  int32_t y;
                }};

                static struct {{ int32_t rc; uint16_t const data[2]; }} const moonbit_string_literal_{n} =
                  {{ 1, {{104, 0}} }};

                int32_t _M0FP11a3add(int32_t, int32_t);

                static int32_t _M0FP11a4callC{n}l9(int32_t);

                static int32_t _M0FP11b4only(int32_t);

                #define _M0FP11b3ffi b_real

                #ifndef Moonbit_unused
                #define Moonbit_unused _M0FP11c3zzz
                #endif

                int32_t b_real(int32_t);

                {extra}
                static int32_t _M0FP11a4callC{n}l9(int32_t _M0L1xS{n}) {{
                  int32_t _M0L6_2atmpS{n + 1} = _M0L1xS{n} + (int32_t)moonbit_string_literal_{n}.data[0];
                  goto joinlet_{n};
                  joinlet_{n}:
                  return _M0L6_2atmpS{n + 1};
                }}

                int32_t _M0FP11a3add(int32_t a, int32_t b) {{
                  struct _M0TP11a1T t = {{ .x = a }};
                  return t.x + b + _M0FP11a4callC{n}l9(0);
                }}

                static int32_t _M0FP11b4only(int32_t _M0L1yS{n + 7}) {{
                  struct _M0TP11b1U u = {{ _M0L1yS{n + 7} }};
                  return u.y + _M0FP11b3ffi(0);
                }}

                void moonbit_init() {{
                }}

                int main(int argc, char** argv) {{
                  moonbit_init();
                  printf("%d\\n", _M0FP11a3add(1, 2) + _M0FP11b4only(3));
                  return 0;
                }}
                ''')
        one, m = csplit.split(prog(12), 2, 'stable')
        two, _ = csplit.split(prog(345, 'int32_t _M0FP11c5otherC9l9(int32_t);\n'), 2, 'stable')
        units = sorted(n for n in one if n not in ('decls.h', 'externs.h', 'data.c', 'init.c'))
        self.assertEqual(units, ['s0.c'])  # (two small packages: together)
        for n in units:
            self.assertEqual(one[n], two[n], n)
        u = one['s0.c']
        self.assertNotIn('S12', u)
        self.assertNotIn('joinlet_12', u)
        self.assertNotIn('moonbit_string_literal_12', u)
        self.assertIn('t.x', u)  # a member stays
        self.assertIn('int32_t _M0FP11a3add(int32_t a', u)  # not static: its name kept
        self.assertGreater(m['stats']['renamed'], 0)
        # a unit has what it uses only: package b's alone does not declare a's type
        # (a's functions over half a unit: a unit of its own; b's under: with the other small ones)
        apart, _ = csplit.split(prog(12), 2, 'stable', unit_bytes=600)
        self.assertEqual(sorted(n for n in apart if n.endswith('.c') and n not in ('data.c', 'init.c')), ['a.c', 's0.c'])
        # (the types renamed too: by their members)
        self.assertIn('int32_t y;', apart['s0.c'])
        self.assertNotIn('int32_t x;', apart['s0.c'])
        self.assertIn('int32_t x;', apart['a.c'])
        self.assertNotIn('int32_t y;', apart['a.c'])
        self.assertIn('int32_t b_real(int32_t);', apart['s0.c'])  # what an FFI name stands for
        # a directive group in the units that use what it defines only (the test driver's FFI name is each program's)
        self.assertIn('#define _M0FP11b3ffi b_real', apart['s0.c'])
        self.assertNotIn('#define _M0FP11b3ffi', apart['a.c'])
        self.assertNotIn('Moonbit_unused', apart['a.c'] + apart['s0.c'])

    def test_by_content_apart(self):
        """String literals and layouts named by their content: two contents whose hashes are the same named apart,
        the same each time; two layouts the same, one name (and the first's offset)."""
        src = PRELUDE + '\n' + textwrap.dedent('''\
            struct _M0TP11a1T;

            static struct { int32_t rc; uint16_t const data[2]; } const moonbit_string_literal_3 = { 1, {104, 0} };

            static struct { int32_t rc; uint16_t const data[2]; } const moonbit_string_literal_9 = { 1, {105, 0} };

            static uint32_t const moonbit_layout_table_data[7] = { 1, 0, 2, 1, 2, 1, 0 };

            int32_t _M0FP11a3add(int32_t, int32_t);

            int32_t _M0FP11a3add(int32_t a, int32_t b) {
              uint32_t x = Moonbit_make_regular_object_header(MOONBIT_REGULAR_LAYOUT_CLASS_INDEXED, 0, 0);
              uint32_t y = Moonbit_make_regular_object_header(MOONBIT_REGULAR_LAYOUT_CLASS_INDEXED, 2, 0);
              uint32_t z = Moonbit_make_regular_object_header(MOONBIT_REGULAR_LAYOUT_CLASS_INDEXED, 5, 0);
              return (int32_t)(x + y + z) + moonbit_string_literal_3.data[0] + moonbit_string_literal_9.data[0];
            }

            void moonbit_init() {
            }

            int main(int argc, char** argv) {
              moonbit_init();
              return _M0FP11a3add(1, 2);
            }
            ''')

        def names(files):
            u = ''.join(t for n, t in files.items() if n.endswith('.c') and n not in ('data.c', 'init.c'))
            lay = re.findall(r'INDEXED, (csplit_layout_\w+), 0', u)
            lit = sorted(set(re.findall(r'\b(_Ms\w+)\.data', u)))
            return lay, lit, files['data.c']
        lay, lit, data = names(csplit.split(src, 2, 'stable')[0])
        self.assertEqual(lay[0], lay[2])  # offsets 0 and 5: the same words
        self.assertNotEqual(lay[0], lay[1])
        self.assertEqual(len(lit), 2)
        self.assertIn(f'const uint32_t {lay[0]} = 0;', data)  # (the first of the two)
        real = csplit.content_hash
        csplit.content_hash = lambda text: '0'  # every content the same hash
        try:
            for _ in range(2):
                lay2, lit2, data2 = names(csplit.split(src, 2, 'stable')[0])
                self.assertEqual(lay2[0], lay2[2])
                self.assertNotEqual(lay2[0], lay2[1])
                self.assertEqual(sorted(lay2[:2]), ['csplit_layout_0', 'csplit_layout_0_1'])
                self.assertEqual(lit2, ['_Ms0', '_Ms0_1'])
                self.assertIn(f'const uint32_t {lay2[1]} = 2;', data2)
        finally:
            csplit.content_hash = real

    def refuse(self, src, words):
        with self.assertRaises(csplit.SplitError) as e:
            csplit.split(src, 2)
        self.assertIn(words, str(e.exception))

    def test_refusals(self):
        self.refuse('int x;\n', 'not the file moonc generates')
        self.refuse(PRELUDE + ITEMS.replace('void moonbit_init() {', 'void moonbit_init2() {'), 'moonbit_init')
        self.refuse(PRELUDE + ITEMS + '#define LATE 1\n', 'after the first function definition')
        self.refuse(PRELUDE + ITEMS.replace('int32_t _M0G2;', '#if X\nint32_t _M0G2;\n#endif'), 'inside a #if')
        self.refuse(PRELUDE + ITEMS.replace('int32_t _M0G2;', 'int32_t _M0G2, _M0G4;'), 'more than one declarator')
        self.refuse(PRELUDE + ITEMS.replace('int32_t _M0G2;', 'int32_t _M0G2; int32_t _M0G4;'), 'does not end its line')
        self.refuse(PRELUDE + ITEMS + 'int32_t _M0G1 = 2;\n', 'defined twice')
        self.refuse(PRELUDE + ITEMS + 'int32_t f() {\n', 'ends inside an item')


def run(cmd, **kw):
    """The command's output (its stderr shown when it fails)."""
    p = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, **kw)
    if p.returncode != 0:
        raise AssertionError(f'{" ".join(cmd)}: exit {p.returncode}\n{p.stdout.decode()[-2000:]}{p.stderr.decode()[-3000:]}')
    return p.stdout.decode()


CC = shutil.which('cc') or shutil.which('clang') or shutil.which('gcc')


@unittest.skipUnless(CC, 'no C compiler')
class Build(unittest.TestCase):
    def test_made_up_program(self):
        """The made-up file whole and split: the same output."""
        with tempfile.TemporaryDirectory() as t:
            src = os.path.join(t, 'p.c')
            with open(src, 'w') as f:
                f.write(SRC)
            run([CC, src, '-o', os.path.join(t, 'whole')])
            objs = run([sys.executable, os.path.join(HERE, 'mbc.py'), 'compile', '--cc', CC, '--obj',
                        os.path.join(t, 'o'), src]).split()
            exe = os.path.join(t, 'split')
            mbc = [sys.executable, os.path.join(HERE, 'mbc.py'), 'link', '--out', exe, '--']
            said = lambda more=[]: subprocess.run(mbc + [CC] + objs + more + ['-o', exe],
                                                  stderr=subprocess.PIPE).stderr.decode()
            self.assertIn('linked split', said())
            self.assertIn('linked already', said())  # the same objects and command: no link
            self.assertIn('linked split', said(['-lm']))  # another command: linked again
            self.assertEqual(run([os.path.join(t, 'whole')]), run([os.path.join(t, 'split')]))
            self.assertEqual(run([os.path.join(t, 'split')]).strip(), '121')  # 3 + 3 + 104 + 2 + 0 + 1 + 2 + 6


@unittest.skipUnless(CC, 'no C compiler')
class Kept(unittest.TestCase):
    def test_what_an_object_is_made_of(self):
        """An object is kept only when its command, its compiler and every header it includes are as they were: a
        header changed, the flags changed or the compiler changed, it is compiled again."""
        with tempfile.TemporaryDirectory() as t:
            src = os.path.join(t, 'p.c')
            with open(src, 'w') as f:
                f.write(SRC)
            with open(os.path.join(t, 'h.h'), 'w') as f:
                f.write('#define H 1\n')
            extra = os.path.join(t, 'x.c')
            with open(extra, 'w') as f:
                f.write('#include "h.h"\nint x_value(void) { return H; }\n')
            cc = os.path.join(t, 'cc.sh')

            def wrapper(note):
                with open(cc, 'w') as f:
                    f.write(f'#!/bin/sh\n# {note}\nexec {CC} "$@"\n')
                os.chmod(cc, 0o755)
            wrapper('one')

            def compiled(flags='-O1'):
                p = subprocess.run([sys.executable, os.path.join(HERE, 'mbc.py'), 'compile', '--cc', cc,
                                    '--cflags=' + flags + ' -I' + t, '--extra', extra, '--obj', os.path.join(t, 'o'),
                                    src], stdout=subprocess.PIPE, stderr=subprocess.PIPE)
                self.assertEqual(p.returncode, 0, p.stderr.decode())
                m = re.search(r'(\d+) of (\d+) compiled', p.stderr.decode())
                return int(m.group(1)), int(m.group(2))
            n, total = compiled()
            self.assertEqual(n, total)
            self.assertEqual(compiled(), (0, total))  # nothing changed: all kept
            with open(os.path.join(t, 'h.h'), 'w') as f:
                f.write('#define H 2\n')
            self.assertEqual(compiled(), (1, total))  # the header x.c includes: x.c alone
            self.assertEqual(compiled('-O2'), (total, total))  # the flags
            self.assertEqual(compiled('-O2'), (0, total))
            wrapper('two')
            self.assertEqual(compiled('-O2'), (total, total))  # the compiler (its wrapper here)


@unittest.skipUnless(CC, 'no C compiler')
class Store(unittest.TestCase):
    def test_shared_between_programs(self):
        """MBC_STORE: the same unit of another program (the same text, command and compiler) taken, not compiled; a
        header it includes changed, compiled."""
        with tempfile.TemporaryDirectory() as t:
            with open(os.path.join(t, 'h.h'), 'w') as f:
                f.write('#define H 1\n')
            with open(os.path.join(t, 'p.c'), 'w') as f:
                f.write(SRC)
            extra = os.path.join(t, 'x.c')
            with open(extra, 'w') as f:
                f.write('#include "h.h"\nint x_value(void) { return H; }\n')
            env = dict(os.environ, MBC_STORE=os.path.join(t, 'store'))

            def compiled(objdir):
                p = subprocess.run([sys.executable, os.path.join(HERE, 'mbc.py'), 'compile', '--cc', CC, '--cflags=-O1',
                                    '--extra', extra, '--obj', os.path.join(t, objdir), os.path.join(t, 'p.c')],
                                   stdout=subprocess.PIPE, stderr=subprocess.PIPE, env=env)
                self.assertEqual(p.returncode, 0, p.stderr.decode())
                m = re.search(r'(\d+) of (\d+) compiled', p.stderr.decode())
                return int(m.group(1)), int(m.group(2))
            n, total = compiled('a')
            self.assertEqual(n, total)
            self.assertEqual(compiled('b'), (0, total))  # another program's objects: all from the store
            with open(os.path.join(t, 'h.h'), 'w') as f:
                f.write('#define H 2\n')
            self.assertEqual(compiled('c'), (1, total))  # x.c's header changed: x.c compiled
            # two programs at once (moon builds them side by side): each unit compiled by one of them
            env['MBC_STORE'] = os.path.join(t, 'store2')
            cmd = lambda objdir: [sys.executable, os.path.join(HERE, 'mbc.py'), 'compile', '--cc', CC, '--cflags=-O1',
                                  '--extra', extra, '--obj', os.path.join(t, objdir), os.path.join(t, 'p.c')]
            ps = [subprocess.Popen(cmd(o), stdout=subprocess.PIPE, stderr=subprocess.PIPE, env=env) for o in ('d', 'e')]
            done = [p.communicate()[1].decode() for p in ps]
            self.assertTrue(all(p.returncode == 0 for p in ps), done)
            n = sum(int(re.search(r'(\d+) of \d+ compiled', e).group(1)) for e in done)
            self.assertEqual(n, total)


@unittest.skipUnless(CC and shutil.which('moon'), 'no moon or C compiler')
class Moon(unittest.TestCase):
    def test_moonc_program(self):
        """A MoonBit program (closures, strings, globals, a trait, a map) generated by moon: whole and split, the same
        output and the same global symbols (mbc.py check)."""
        with tempfile.TemporaryDirectory() as t:
            os.makedirs(os.path.join(t, 'src', 'main'))
            with open(os.path.join(t, 'moon.mod'), 'w') as f:
                f.write('name = "t/split"\n\nversion = "0.1.0"\n\nsource = "src"\n')
            with open(os.path.join(t, 'src', 'main', 'moon.pkg'), 'w') as f:
                f.write('options(\n  "is-main": true,\n)\n')
            with open(os.path.join(t, 'src', 'main', 'main.mbt'), 'w') as f:
                f.write(textwrap.dedent('''\
                    let greeting : String = "hello from a global"

                    let table : Map[String, Int] = { "one": 1, "two": 2, "three": 3 }

                    trait Shape {
                      area(Self) -> Double
                    }

                    struct Square(Double)

                    impl Shape for Square with area(self) { self.0 * self.0 }

                    fn total(shapes : Array[&Shape]) -> Double {
                      shapes.fold(init=0.0, fn(acc, s) { acc + s.area() })
                    }

                    fn main {
                      println(greeting)
                      let adders = Array::makei(5, fn(i) { fn(x : Int) { x + i } })
                      let mut sum = 0
                      for f in adders {
                        sum = sum + f(10)
                      }
                      println("sum \\{sum}")
                      println("two is \\{table.get("two")}")
                      println("area \\{total([Square(2.0), Square(3.0)])}")
                    }
                    '''))
            mbc = os.path.join(HERE, 'mbc.py')
            c = run([sys.executable, mbc, 'gen', '--dir', t, 'src/main']).strip().splitlines()[-1]
            self.assertTrue(c.endswith('main.c'), c)
            moon_home = os.environ.get('MOON_HOME') or os.path.dirname(os.path.dirname(shutil.which('moon')))
            inc = os.path.join(moon_home, 'include')
            rt = os.path.join(moon_home, 'lib', 'runtime')
            flags = f'-I{inc} -fwrapv -fno-strict-aliasing -Wno-unused-value -O2 -DMOONBIT_ALLOCATOR=MOONBIT_ALLOCATOR_SYSTEM'
            # the runtime's files as the Android build has them (one a platform cannot compile is left out)
            rts = [os.path.join(rt, f + '.c') for f in ('runtime', 'env', 'utf', 'sync_io', 'backtrace')]
            objs = run([sys.executable, mbc, 'compile', '--cc', CC, '--cflags=' + flags, '--obj',
                        os.path.join(t, 'o')] + ['--optional=' + r for r in rts] + [c]).split()
            rts = [o for o in objs if '/x_' in o]
            run([CC] + objs + ['-lm', '-o', os.path.join(t, 'split')])
            run([CC] + flags.split() + [c] + rts + ['-lm', '-o', os.path.join(t, 'whole')])
            out = run([os.path.join(t, 'whole')])
            self.assertIn('sum 60', out)
            self.assertEqual(out, run([os.path.join(t, 'split')]))
            self.assertEqual(run([sys.executable, mbc, 'check', '--cc', CC, '--cflags=' + flags, '--obj',
                                  os.path.join(t, 'k'), c]).strip(), 'ok')


