// Writes classes.mbt (node station/mb/src/history/gen.mjs station/mb/src/history/classes.mbt) from this node's Unicode
// properties: Alphabetic, and Alphabetic or Numeric, as transcript.ts's code-mode reading tests characters.
import { writeFileSync } from "node:fs";
const ranges = (re) => { const out = []; let start = -1;
  for (let c = 0; c <= 0x110000; c++) {
    const ok = c <= 0x10FFFF && !(c >= 0xD800 && c <= 0xDFFF) && re.test(String.fromCodePoint(c));
    if (ok && start < 0) start = c; if (!ok && start >= 0) { out.push(start, c - 1); start = -1; } }
  return out; };
const fmt = (xs) => xs.map((x) => `0x${x.toString(16)}`).join(", ");
writeFileSync(process.argv[2], `// Generated by node ${process.version} (Unicode ${process.versions.unicode}) by gen.mjs beside this: the code points of
// \\p{Alphabetic} and of [\\p{Alphabetic}\\p{N}], as ranges. Do not edit.

///|
let alphabetic_ranges : FixedArray[Int] = [${fmt(ranges(/^\p{Alphabetic}$/u))}]

///|
let alphanumeric_ranges : FixedArray[Int] = [${fmt(ranges(/^[\p{Alphabetic}\p{N}]$/u))}]
`);
