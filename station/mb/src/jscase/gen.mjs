// Writes tables.mbt (node station/mb/src/jscase/gen.mjs station/mb/src/jscase/tables.mbt) from this node's String.prototype.toLowerCase and Unicode properties.
import { writeFileSync } from "node:fs";
const pairs = [], cased = [], ignorable = [];
const ranges = (re) => { const out = []; let start = -1;
  for (let c = 0; c <= 0x110000; c++) {
    const ok = c <= 0x10FFFF && !(c >= 0xD800 && c <= 0xDFFF) && re.test(String.fromCodePoint(c));
    if (ok && start < 0) start = c; if (!ok && start >= 0) { out.push([start, c - 1]); start = -1; } }
  return out; };
for (let c = 0; c <= 0x10FFFF; c++) {
  if (c >= 0xD800 && c <= 0xDFFF) continue;
  const s = String.fromCodePoint(c), l = s.toLowerCase();
  if (l !== s && [...l].length === 1) pairs.push([c, l.codePointAt(0)]);
}
// The code points whose upper and lower case differ (c.toUpperCase() !== c.toLowerCase()).
const changing = ranges({ test: (c) => c.toUpperCase() !== c.toLowerCase() });
const fmt = (xs) => xs.map((x) => `0x${x.toString(16)}`).join(", ");
const out = `// Generated by node ${process.version} (V8's String.prototype.toLowerCase, ICU ${process.versions.icu}, Unicode ${process.versions.unicode}): each
// code point that lowers to one other (U+0130 lowers to two, and U+03A3 by its context, in jscase.mbt), and the
// Cased and Case_Ignorable properties the final sigma is decided by, and the code points whose cases differ. Do not edit; made again with the node the station
// runs, by gen.mjs beside this.

///|
let lower_from : FixedArray[Int] = [${fmt(pairs.map((p) => p[0]))}]

///|
let lower_to : FixedArray[Int] = [${fmt(pairs.map((p) => p[1]))}]

///|
let cased_ranges : FixedArray[Int] = [${fmt(ranges(/\p{Cased}/u).flat())}]

///|
let ignorable_ranges : FixedArray[Int] = [${fmt(ranges(/\p{Case_Ignorable}/u).flat())}]

///|
let changing_ranges : FixedArray[Int] = [${fmt(changing.flat())}]
`;
writeFileSync(process.argv[2], out);
